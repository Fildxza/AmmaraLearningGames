// Exports the research dataset: research/questions.json, research/questions.csv, research/summary.json
// and the numeric tables inside research/RESEARCH-REPORT.md. Run: npm run research
import fs from 'node:fs';
import path from 'node:path';
import { buildDataset, summarise, ROOT } from './lib/research.mjs';
import { toCSV } from '../src/engine/core/csv.js';

const ds = buildDataset();
const sum = summarise(ds);
const out = (p) => path.join(ROOT, p);

fs.writeFileSync(out('research/questions.json'), JSON.stringify({
  generated: new Date().toISOString(), note: 'One record per question. verificationStatus: fact-checked-against-source | visual-identification-low-risk | needs-human-review. No question has been reviewed by a human teacher.',
  count: ds.records.length, questions: ds.records
}, null, 1));

const headers = ['id', 'category', 'objective', 'ages', 'difficulty', 'interaction_type', 'question_ms', 'question_en', 'option_1_id', 'option_2_id', 'option_3_id', 'option_1_en', 'option_2_en', 'option_3_en',
  'correct_answer_id', 'correct_index', 'correct_ms', 'correct_en', 'hint_ms', 'hint_en', 'explanation_ms', 'explanation_en', 'big_picture', 'sources', 'developmental_alignment', 'verification_status', 'human_reviewed', 'languages', 'accessibility'];
const rows = ds.records.map((r) => [r.id, r.category, r.objective, r.recommendedAges.join(' '), r.difficulty, r.interactionType, r.question.ms, r.question.en,
  ...[0, 1, 2].map((i) => (r.options[i] ? r.options[i].id : '')), ...[0, 1, 2].map((i) => (r.options[i] ? r.options[i].label.en : '')),
  r.correctAnswerId, r.correctIndex, r.correctLabel.ms, r.correctLabel.en, r.hint ? r.hint.ms : '', r.hint ? r.hint.en : '', r.explanation ? r.explanation.ms : '', r.explanation ? r.explanation.en : '',
  r.illustration.bigPicture || '', r.sources.join(' '), r.developmentalAlignment ? `${r.developmentalAlignment.source}: ${r.developmentalAlignment.milestone}` : '', r.verificationStatus, 'no', r.languages.join(' '), r.accessibility]);
fs.writeFileSync(out('research/questions.csv'), toCSV(headers, rows));
fs.writeFileSync(out('research/summary.json'), JSON.stringify(sum, null, 1));

// ---- the report -------------------------------------------------------------------------------------------------
const src = ds.sources.sources;
const byStatus = (s) => src.filter((x) => x.status === s);
const catRows = Object.entries(sum.perCategory).map(([k, v]) => `| ${k} | ${v.questions} | ${v.distinctQuestionAnswerPairs} | ${v.objectives} | ${v.factChecked} | ${v.lowRiskVisual} | ${v.needsHumanReview} |`).join('\n');
const needs = ds.records.filter((r) => r.verificationStatus === 'needs-human-review');
const report = `# AmmaraGames: research report

Generated by \`npm run research\` on ${new Date().toISOString().slice(0, 10)}. All figures below are computed from the files in this folder.

## What was and was not done

* **Reviewed questions:** the question bank has **${sum.total}** questions. "Reviewed" here means *checked by automated validators and by the build assistant*. **No question has been reviewed by a human teacher or a native Malay speaker.** The CSV has a \`human_reviewed\` column that is "no" on every row so a teacher can fill it in.
* **Unique questions:** ${sum.total} distinct ids; ${Object.values(sum.perCategory).reduce((a, v) => a + v.distinctQuestionAnswerPairs, 0)} distinct (question, answer) pairs, so no two questions are the same item reworded. Every one of the 15 learning categories has at least 20 questions (target met; see the table).
* **Objectives:** ${sum.objectivesUsed} different learning objectives are used (\`objectives.json\`).

## Questions per category

| Category | Questions | Distinct question+answer | Objectives | Fact-checked vs a fetched source | Low-risk picture identification | Needs human review |
|---|---|---|---|---|---|---|
${catRows}

By age group (a question can serve several): 2-3: ${sum.perAge['2-3']}, 3-4: ${sum.perAge['3-4']}, 4+: ${sum.perAge['4+']}.
By difficulty: easy ${sum.perDifficulty[1]}, medium ${sum.perDifficulty[2]}, harder ${sum.perDifficulty[3]}.
By interaction type: ${Object.entries(sum.perInteractionType).map(([k, v]) => `${k} ${v}`).join(', ')}.
By verification status: ${Object.entries(sum.perVerificationStatus).map(([k, v]) => `${k} ${v}`).join(', ')}.

## Sources actually accessed

${byStatus('fetched').map((s) => `* **${s.title}** (${s.url}): ${s.use}`).join('\n')}

## Sources reached only through search-result summaries

These were *not* opened; only the text shown in a search result was seen, so they are weak evidence.

${byStatus('search-snippet').map((s) => `* ${s.title}: ${s.use}`).join('\n')}

## Sources that could not be accessed

${byStatus('failed').map((s) => `* ${s.title} (${s.url}): ${s.use}`).join('\n')}

Google Search / Google Images were not used for images. Pinterest returned no readable content. Canva was used only to read a public template listing for activity ideas. Wikimedia Commons was unreachable. Openverse's API was queried once to see what licences cartoon images carry (mostly CC BY-ND or BY-SA, which are awkward for bundling), and nothing was downloaded.

## How content was verified

1. **Automated validator** (\`src/engine/core/validate.js\`, 28 unit tests in \`tests/unit\`): duplicate ids, empty prompts, 2-4 distinct choices, every choice has a picture and a label in both languages, the answer is one of the choices, ages and types are valid, hints and explanations exist in both languages, the big picture never reveals the answer except in "match" questions, and for letter-sound questions no distractor starts with the same letter in either language. Seeded random tests prove the correct answer is tracked by its id, never by its position.
2. **Fact checks** (\`fact-checks.json\`): ${ds.checks.length} claim groups covering ${new Set(ds.checks.flatMap((c) => c.questions)).size} questions were compared with pages that were actually read (CDC handwashing, AAP toothbrushing, NASA Space Place, DBP dictionary, a Safe Kids search summary). Each entry says whether the evidence is an exact quote or the assistant's paraphrase.
3. **Developmental alignment**: some objectives are linked to a CDC milestone statement copied from the CDC pages fetched. Where the link is only loose, \`alignmentStrength\` says "related".

## Original visual and audio assets

All ~220 answer pictures, the playroom, 38 station landmarks, the character, accessories, logo, music and sound effects are original and generated by code. The only third-party items are the Fredoka font (SIL OFL 1.1) and Three.js (MIT); see \`asset-attributions.json\`.

## What still needs human review

* **${needs.length} questions** are marked \`needs-human-review\` because they contain an everyday or scientific claim that was not compared with a source (for example animal sounds and habitats, plant needs, weather, the Sun and Moon, colour mixing, safety and manners). Filter \`questions.csv\` on \`verification_status\`.
* **Bahasa Melayu and English wording** of all questions, hints and explanations was written by the build assistant; a native speaker/teacher should read it, especially the child-directed phrasing.
* **Mapping to the official Malaysian preschool standard (KSPK 2017)** was not done: the official KPM document was not read.
* **Local culture check:** examples lean Malaysian (durian, rambutan, bas sekolah, tocang, hijab hairstyle); a teacher should confirm they fit the class.
* **Pronunciation of read-aloud voices** depends on the voices installed on the school computer.

## Automated content checks

Run \`npm test\`. At the time of writing: shipped configuration has 0 errors; ${sum.total} questions are valid; every station has questions for every age group; both languages are complete for all prompts, hints, explanations and answer labels.
`;
fs.writeFileSync(out('research/RESEARCH-REPORT.md'), report);
console.log(`Exported ${ds.records.length} question records (json + csv), summary and report to research/. Needs human review: ${needs.length}.`);
